@app.put("/communities/{community_id}/profile")
def update_community_profile(
    community_id: int,
    name: str | None = None,
    description: str | None = None,
    avatar_url: str | None = None,
    visibility: str | None = None,
    username: str | None = None,
    authorization: str | None = Header(default=None)
):
    user = get_current_user(authorization)
    c = db()

    row = c.execute(
        """SELECT * FROM communities WHERE id=%s""",
        (community_id,)
    ).fetchone()

    if not row:
        c.close()
        raise HTTPException(status_code=404, detail="یافت نشد.")

    if row["owner_id"] != user["id"]:
        c.close()
        raise HTTPException(status_code=403, detail="فقط مالک می‌تواند ویرایش کند.")

    if visibility is not None and visibility not in ("public", "private"):
        c.close()
        raise HTTPException(status_code=400, detail="نوع دسترسی نامعتبر است.")

    if username:
        username = username.strip().lower().lstrip("@")
        existing = c.execute(
            "SELECT id FROM communities WHERE username=%s AND id<>%s",
            (username, community_id)
        ).fetchone()
        if existing:
            c.close()
            raise HTTPException(status_code=409, detail="این نام کاربری قبلاً استفاده شده است.")

    c.execute(
        """
        UPDATE communities
        SET name=COALESCE(%s,name),
            description=COALESCE(%s,description),
            avatar_url=COALESCE(%s,avatar_url),
            visibility=COALESCE(%s,visibility),
            username=COALESCE(%s,username)
        WHERE id=%s
        """,
        (name, description, avatar_url, visibility, username, community_id)
    )
    c.commit()

    updated = c.execute(
        "SELECT * FROM communities WHERE id=%s",
        (community_id,)
    ).fetchone()
    c.close()

    return {"message":"ویرایش شد","community":dict(updated)}


