def get_current_user(
    authorization: str | None
):

    if not authorization:
        raise HTTPException(
            status_code=401,
            detail="ورود لازم است."
        )

    if not authorization.startswith(
        "Bearer "
    ):
        raise HTTPException(
            status_code=401,
            detail="توکن نامعتبر است."
        )

    token = authorization[7:]

    try:

        payload = jwt.decode(
            token,
            SECRET_KEY,
            algorithms=[ALGORITHM]
        )

        user_id = int(
            payload["sub"]
        )

    except Exception:

        raise HTTPException(
            status_code=401,
            detail="جلسه شما منقضی شده است."
        )

    connection = db()

    session = connection.execute(
        """
        SELECT id
        FROM sessions
        WHERE token = %s
          AND user_id = %s
        LIMIT 1
        """,
        (token, user_id)
    ).fetchone()

    if not session:
        connection.close()
        raise HTTPException(
            status_code=401,
            detail="این نشست دیگر فعال نیست. دوباره وارد شوید."
        )

    user = connection.execute(
        """
        SELECT *
        FROM users
        WHERE id = %s
        """,
        (user_id,)
    ).fetchone()

    if user:
        connection.execute(
            """
            UPDATE sessions
            SET last_seen = %s
            WHERE id = %s
            """,
            (
                datetime.now(timezone.utc).isoformat(),
                session["id"]
            )
        )
        connection.commit()

    connection.close()

    if not user:

        raise HTTPException(
            status_code=401,
            detail="کاربر پیدا نشد."
        )

    # =========================
    # BLOCK CHECK
    # =========================

    if user["role"] != "owner":

        connection = db()

        block = connection.execute(
            """
            SELECT
                block_type,
                block_until
            FROM blocks
            WHERE user_id = %s
            """,
            (user["id"],)
        ).fetchone()

        if block:

            block_until = block["block_until"]

            if (
                block["block_type"] == "permanent"
                or
                (
                    block_until
                    and datetime.fromisoformat(
                        block_until
                    ) > datetime.now(timezone.utc)
                )
            ):

                connection.close()

                if block["block_type"] == "permanent":
                    detail = "این حساب برای همیشه مسدود شده است."
                elif block["block_type"] == "6_months":
                    detail = "این حساب به مدت ۶ ماه مسدود شده است."
                else:
                    detail = "این حساب به مدت ۱ ماه مسدود شده است."

                raise HTTPException(
                    status_code=403,
                    detail=detail
                )

            # block expired
            connection.execute(
                """
                DELETE FROM blocks
                WHERE user_id = %s
                """,
                (user["id"],)
            )

            connection.execute(
                """
                UPDATE users
                SET blocked = 0
                WHERE id = %s
                """,
                (user["id"],)
            )

            connection.commit()

        connection.close()

    return user


