@app.post("/messages")
async def send_message(
    receiver_username: str,
    text: str = "",
    media_url: str | None = None,
    media_type: str | None = None,
    media_filename: str | None = None,
    media_size: int = 0,
    authorization: str | None = Header(
        default=None
    )
):

    sender = get_current_user(
        authorization
    )

    connection = db()

    receiver = connection.execute(
        """
        SELECT *
        FROM users
        WHERE username = %s
        """,
        (receiver_username,)
    ).fetchone()

    if not receiver:

        connection.close()

        raise HTTPException(
            status_code=404,
            detail="کاربر پیدا نشد."
        )

    if receiver["blocked"]:

        connection.close()

        raise HTTPException(
            status_code=403,
            detail="این حساب در دسترس نیست."
        )

    # User-to-user block: ارسال در هر دو جهت ممنوع است
    block_row = connection.execute(
        """
        SELECT blocker_id, blocked_id
        FROM user_blocks
        WHERE
            (blocker_id = %s AND blocked_id = %s)
            OR
            (blocker_id = %s AND blocked_id = %s)
        LIMIT 1
        """,
        (
            sender["id"],
            receiver["id"],
            receiver["id"],
            sender["id"]
        )
    ).fetchone()

    if block_row:

        connection.close()

        if block_row["blocker_id"] == receiver["id"]:
            raise HTTPException(
                status_code=403,
                detail="مسدود شدی. امکان ارسال پیام وجود ندارد."
            )
        else:
            raise HTTPException(
                status_code=403,
                detail="این کاربر را مسدود کرده‌ای. امکان ارسال پیام وجود ندارد."
            )

    if not text.strip() and not media_url:

        connection.close()

        raise HTTPException(
            status_code=400,
            detail="پیام خالی است."
        )

    cursor = connection.execute(
        """
        INSERT INTO messages
        (
            sender_id,
            receiver_id,
            text,
            media_url,
            media_type,
            media_filename,
            media_size,
            created_at
        )
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
        RETURNING id
        """,
        (
            sender["id"],
            receiver["id"],
            text.strip(),
            media_url,
            media_type,
            media_filename,
            media_size,
            datetime.now(
                timezone.utc
            ).isoformat()
        )
    )

    message_id = cursor.fetchone()["id"]

    connection.commit()

    connection.close()

    return {
        "message": "Message sent",
        "id": message_id
    }



