def valid_username(username: str):

    return bool(
        re.fullmatch(
            r"[A-Za-z0-9_]{3,20}",
            username
        )
    )


def valid_email(email: str):

    return bool(
        re.fullmatch(
            r"[^@\s]+@gmail\.com",
            email,
            re.IGNORECASE
        )
    )


def valid_password(password: str):

    return (
        len(password) >= 8
        and bool(re.search(r"[A-Z]", password))
        and bool(re.search(r"[a-z]", password))
        and bool(re.search(r"[0-9]", password))
        and bool(re.search(r"[^A-Za-z0-9]", password))
    )


