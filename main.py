    connection = db()

    row = connection.execute(
        """
        SELECT
            s.id,
            s.duration,
            s.starts_at,
            s.ends_at,
            s.reason,
            s.created_at,
            u.username AS moderator_username,
            u.name AS moderator_name
        FROM user_suspensions s
        LEFT JOIN users u
          ON u.id = s.moderator_id
        WHERE s.user_id = %s
        ORDER BY s.id DESC
        LIMIT 1
        """,
        (user["id"],)
    ).fetchone()

    connection.close()

    if not row:
        return {"suspended": False}

    if row["ends_at"]:
        try:
            end = datetime.fromisoformat(
                row["ends_at"].replace("Z", "+00:00")
            )

            if end <= datetime.now(timezone.utc):
                return {"suspended": False}
        except Exception:
            pass

    return {
        "suspended": True,
        **dict(row)
    }


