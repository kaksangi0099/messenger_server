@app.post("/login")
def login(
    data: LoginRequest,
    user_agent: str | None = Header(default=None)
):

    connection = db()

    user = connection.execute(
        """
        SELECT *
        FROM users
        WHERE username = %s
        """,
        (data.username.strip(),)
    ).fetchone()

    connection.close()

    if not user:

        raise HTTPException(
            status_code=401,
            detail="نام کاربری یا رمز عبور اشتباه است."
        )

    if user["blocked"]:

        raise HTTPException(
            status_code=403,
            detail="این حساب توسط مالک برنامه مسدود شده است."
        )

    if not verify_password(
        data.password,
        user["password"]
    ):

        raise HTTPException(
            status_code=401,
            detail="نام کاربری یا رمز عبور اشتباه است."
        )

    # بررسی محرومیت حساب قبل از ایجاد نشست
    connection = db()

    suspension = connection.execute(
        """
        SELECT
            s.duration,
            s.starts_at,
            s.ends_at,
            s.reason,
            u.name AS moderator_name,
            u.username AS moderator_username
        FROM user_suspensions s
        LEFT JOIN users u
          ON u.id = s.moderator_id
        WHERE s.user_id = %s
        ORDER BY s.id DESC
        LIMIT 1
        """,
        (user["id"],)
    ).fetchone()

    connection.close()

    if suspension:
        if suspension["ends_at"] is None:
            raise HTTPException(
                status_code=403,
                detail=(
                    "حساب شما به‌صورت دائمی محروم شده است. "
                    "این تصمیم توسط مدیریت Media ثبت شده است."
                )
            )

        try:
            suspension_end = datetime.fromisoformat(
                suspension["ends_at"].replace("Z", "+00:00")
            )

            if suspension_end > datetime.now(timezone.utc):
                end_text = suspension_end.strftime(
                    "%Y-%m-%d %H:%M UTC"
                )

                raise HTTPException(
                    status_code=403,
                    detail=(
                        "حساب شما موقتاً از دسترسی به Media محروم شده است. "
                        f"پایان محرومیت: {end_text}. "
                        "در صورت نیاز می‌توانید از پشتیبانی Media پیگیری کنید."
                    )
                )
        except ValueError:
            pass

    token = create_token(user)

    connection = db()
    now = datetime.now(timezone.utc).isoformat()

    connection.execute(
        """
        INSERT INTO sessions
        (
            user_id,
            token,
            created_at,
            last_seen,
            device_name,
            user_agent
        )
        VALUES (%s, %s, %s, %s, %s, %s)
        """,
        (
            user["id"],
            token,
            now,
            now,
            get_device_name(user_agent),
            user_agent or ""
        )
    )
    connection.commit()
    connection.close()

    return {
        "message": "Login successful",
        "access_token": token,
        "user": {
            "id": user["id"],
            "name": user["name"],
            "username": user["username"],
            "email": user["email"],
            "role": user["role"],
            "premium_level": user["premium_level"]
        }
    }


