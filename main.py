@app.post("/communities/{community_id}/messages/{message_id}/forward")
def forward_community_message(
    community_id: int,
    message_id: int,
    receiver_username: str,
    current_user=Depends(get_current_user)
):
    with get_db() as conn:
        cursor = conn.cursor()

        cursor.execute("""
            SELECT cm.id, cm.community_id, cm.sender_id, cm.text,
                   cm.media_url, cm.media_type, cm.media_filename,
                   cm.media_size, cm.created_at,
                   c.name AS community_name,
                   c.username AS community_username
            FROM community_messages cm
            JOIN communities c ON c.id = cm.community_id
            JOIN community_members mem
              ON mem.community_id = cm.community_id
             AND mem.user_id = %s
            WHERE cm.id = %s
              AND cm.community_id = %s
        """, (current_user["id"], message_id, community_id))

        source = cursor.fetchone()

        if not source:
            raise HTTPException(status_code=404, detail="Community message not found")

        cursor.execute("""
            SELECT id
            FROM users
            WHERE username = %s
        """, (receiver_username,))

        receiver = cursor.fetchone()

        if not receiver:
            raise HTTPException(status_code=404, detail="Receiver not found")

        if receiver["id"] == current_user["id"]:
            raise HTTPException(status_code=400, detail="Cannot forward to yourself")

        cursor.execute("""
            INSERT INTO messages (
                sender_id,
                receiver_id,
                text,
                media_url,
                media_type,
                media_filename,
                media_size,
                created_at
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, CURRENT_TIMESTAMP)
            RETURNING id
        """, (
            current_user["id"],
            receiver["id"],
            source["text"] or "",
            source["media_url"],
            source["media_type"],
            source["media_filename"],
            source["media_size"] or 0
        ))

        new_message = cursor.fetchone()
        new_message_id = new_message["id"]

        cursor.execute("""
            INSERT INTO message_forwards (
                message_id,
                source_type,
                source_community_id,
                source_message_id,
                source_name,
                source_username
            )
            VALUES (%s, 'community', %s, %s, %s, %s)
        """, (
            new_message_id,
            community_id,
            message_id,
            source["community_name"] or "",
            source["community_username"] or ""
        ))

        conn.commit()

    return {
        "ok": True,
        "message_id": new_message_id,
        "forwarded": True,
        "source": {
            "type": "community",
            "community_id": community_id,
            "message_id": message_id,
            "name": source["community_name"] or "",
            "username": source["community_username"] or ""
        }
    }


@app.get("/messages/{username}")
def get_messages(
    username: str,
    authorization: str | None = Header(
        default=None
    )
):

    user = get_current_user(
        authorization
    )

    connection = db()

    other = connection.execute(
        """
        SELECT id
        FROM users
        WHERE username = %s
        """,
        (username,)
    ).fetchone()

    if not other:

        connection.close()

        raise HTTPException(
            status_code=404,
            detail="کاربر پیدا نشد."
        )

    rows = connection.execute(
        """
        SELECT
            m.id,
            m.sender_id,
            m.receiver_id,
            m.text,
            m.media_url,
            m.media_type,
            m.media_filename,
            m.media_size,
            m.created_at,
            mf.source_type AS forward_source_type,
            mf.source_community_id AS forward_community_id,
            mf.source_message_id AS forward_message_id,
            mf.source_name AS forward_source_name,
            mf.source_username AS forward_source_username,
            CASE
                WHEN EXISTS (
                    SELECT 1
                    FROM message_receipts mr
                    WHERE mr.message_id = m.id
                    AND mr.delivered_at IS NOT NULL
                ) THEN 1 ELSE 0
            END AS delivered,
            CASE
                WHEN EXISTS (
                    SELECT 1
                    FROM message_receipts mr
                    WHERE mr.message_id = m.id
                    AND mr.read_at IS NOT NULL
                ) THEN 1 ELSE 0
            END AS read
        FROM messages m
        LEFT JOIN message_forwards mf
          ON mf.message_id = m.id
        WHERE
            (
                sender_id = %s
                AND receiver_id = %s
            )
            OR
            (
                sender_id = %s
                AND receiver_id = %s
            )
        ORDER BY m.id ASC
        """,
        (
            user["id"],
            other["id"],
            other["id"],
            user["id"]
        )
    ).fetchall()

    connection.close()

    return {
        "messages": [
            dict(row)
            for row in rows
        ]
    }



