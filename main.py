@app.get("/chats")
def get_recent_chats(
    authorization: str | None = Header(default=None)
):
    current = get_current_user(authorization)

    connection = db()

    rows = connection.execute(
        """
        SELECT
            u.id,
            u.name,
            u.username,
            u.role,
            u.premium_level,
            p.avatar_url,
            lm.text AS last_message,
            lm.media_url,
            lm.media_type,
            lm.created_at AS last_message_at
        FROM users u

        JOIN (
            SELECT
                CASE
                    WHEN sender_id = %s THEN receiver_id
                    ELSE sender_id
                END AS other_id,
                MAX(id) AS last_id
            FROM messages
            WHERE
                sender_id = %s
                OR receiver_id = %s
            GROUP BY other_id
        ) recent
            ON recent.other_id = u.id

        JOIN messages lm
            ON lm.id = recent.last_id

        LEFT JOIN profiles p
            ON p.user_id = u.id

        ORDER BY recent.last_id DESC
        """,
        (
            current["id"],
            current["id"],
            current["id"]
        )
    ).fetchall()

    connection.close()

    chats = []

    for row in rows:

        last_message = row["last_message"] or ""

        if not last_message:
            if row["media_type"] == "image":
                last_message = "📷 عکس"
            elif row["media_type"] == "video":
                last_message = "🎬 ویدیو"
            elif row["media_url"]:
                last_message = "📎 فایل"
            else:
                last_message = "پیام"

        chats.append({
            "id": row["id"],
            "name": row["name"],
            "username": row["username"],
            "role": row["role"],
            "premium_level": row["premium_level"],
            "avatar_url": row["avatar_url"],
            "last_message": last_message,
            "last_message_at": row["last_message_at"]
        })

    return {
        "chats": chats
    }



