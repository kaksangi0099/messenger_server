class UserSuspensionRequest(BaseModel):
    duration: str
    reason: str = ""


@app.post("/owner/users/{user_id}/suspend")
def suspend_user(
    user_id: int,
    data: UserSuspensionRequest,
    authorization: str | None = Header(default=None)
):
    owner = require_owner(authorization)

    allowed = {
        "1_month": 30,
        "3_months": 90,
        "1_year": 365,
        "permanent": None
    }

    if data.duration not in allowed:
        raise HTTPException(
            status_code=400,
            detail="مدت محرومیت نامعتبر است."
        )

    connection = db()

    user = connection.execute(
        "SELECT id, username, role FROM users WHERE id = %s",
        (user_id,)
    ).fetchone()

    if not user:
        connection.close()
        raise HTTPException(
            status_code=404,
            detail="کاربر پیدا نشد."
        )

    if user["role"] == "owner":
        connection.close()
        raise HTTPException(
            status_code=403,
            detail="حساب مالک قابل محروم‌سازی نیست."
        )

    # پایان محرومیت
    if data.duration == "permanent":
        ends_at = None
    else:
        from datetime import datetime, timedelta, timezone
        ends_at = (
            datetime.now(timezone.utc)
            + timedelta(days=allowed[data.duration])
        ).isoformat()

    from datetime import datetime, timezone
    now = datetime.now(timezone.utc).isoformat()

    # غیرفعال کردن محرومیت قبلی
    connection.execute(
        """
        UPDATE user_suspensions
        SET ends_at = starts_at
        WHERE user_id = %s
          AND ends_at IS NOT NULL
          AND ends_at > %s
        """,
        (user_id, now)
    )

    connection.execute(
        """
        INSERT INTO user_suspensions
        (user_id, moderator_id, duration, starts_at, ends_at, reason, created_at)
        VALUES (%s, %s, %s, %s, %s, %s, %s)
        """,
        (
            user_id,
            owner["id"],
            data.duration,
            now,
            ends_at,
            data.reason[:500],
            now
        )
    )

    connection.commit()
    connection.close()

    return {
        "message": "حساب کاربر با موفقیت محروم شد.",
        "username": user["username"],
        "duration": data.duration,
        "ends_at": ends_at
    }


