@app.post("/communities/{community_id}/messages")
async def send_community_message(
    community_id: int,
    text: str = "",
    media_url: str | None = None,
    media_type: str | None = None,
    media_filename: str | None = None,
    media_size: int = 0,
    authorization: str | None = Header(default=None)
):
    user = get_current_user(authorization)
    connection = db()

    community = connection.execute(
        "SELECT * FROM communities WHERE id = %s",
        (community_id,)
    ).fetchone()

    if not community:
        connection.close()
        raise HTTPException(status_code=404, detail="گروه یا کانال پیدا نشد.")

    member = connection.execute(
        """
        SELECT role FROM community_members
        WHERE community_id = %s AND user_id = %s
        """,
        (community_id, user["id"])
    ).fetchone()

    if not member:
        connection.close()
        raise HTTPException(status_code=403, detail="عضو این بخش نیستی.")

    # در کانال فقط مالک/ادمین اجازه ارسال دارد
    if community["type"] == "channel" and member["role"] not in ("owner", "admin"):
        connection.close()
        raise HTTPException(status_code=403, detail="فقط مدیر کانال می‌تواند پست بفرستد.")

    if not text.strip() and not media_url:
        connection.close()
        raise HTTPException(status_code=400, detail="پیام خالی است.")

    row = connection.execute(
        """
        INSERT INTO community_messages
        (
            community_id, sender_id, text,
            media_url, media_type, media_filename,
            media_size, created_at
        )
        VALUES (%s,%s,%s,%s,%s,%s,%s,%s)
        RETURNING id
        """,
        (
            community_id,
            user["id"],
            text.strip(),
            media_url,
            media_type,
            media_filename,
            media_size,
            datetime.now(timezone.utc).isoformat()
        )
    ).fetchone()

    connection.commit()
    connection.close()

    return {
        "message": "Community message sent",
        "id": row["id"]
    }



@app.delete("/communities/{community_id}/messages/{message_id}")
def delete_community_message(
    community_id: int,
    message_id: int,
    authorization: str | None = Header(default=None)
):
    user = get_current_user(authorization)
    c = db()

    member = c.execute(
        """
        SELECT role FROM community_members
        WHERE community_id=%s AND user_id=%s
        """,
        (community_id, user["id"])
    ).fetchone()

    if not member:
        c.close()
        raise HTTPException(status_code=403, detail="عضو نیستی.")

    message = c.execute(
        """
        SELECT id, sender_id
        FROM community_messages
        WHERE id=%s AND community_id=%s
        """,
        (message_id, community_id)
    ).fetchone()

    if not message:
        c.close()
        raise HTTPException(status_code=404, detail="پیام پیدا نشد.")

    # مالک/ادمین می‌تواند پیام را حذف کند.
    # در گروه، فرستنده هم می‌تواند پیام خودش را حذف کند.
    allowed = (
        member["role"] in ("owner", "admin")
        or message["sender_id"] == user["id"]
    )

    if not allowed:
        c.close()
        raise HTTPException(status_code=403, detail="اجازه حذف این پیام را نداری.")

    c.execute(
        """
        DELETE FROM community_message_receipts
        WHERE message_id=%s
        """,
        (message_id,)
    )

    c.execute(
        """
        DELETE FROM community_messages
        WHERE id=%s AND community_id=%s
        """,
        (message_id, community_id)
    )

    c.commit()
    c.close()

    return {"ok": True, "deleted_id": message_id}


