@app.get("/users/search")
def search_users(
    q: str,
    authorization: str | None = Header(default=None)
):
    current = get_current_user(authorization)

    q = q.strip()

    if not q:
        return {"users": []}

    connection = db()

    rows = connection.execute(
        """
        SELECT
            id,
            name,
            username,
            role,
            premium_level,
            verified
        FROM users
        WHERE
            username LIKE %s
            OR name LIKE %s
        ORDER BY
            CASE
                WHEN username = %s THEN 0
                WHEN name = %s THEN 1
                ELSE 2
            END,
            id ASC
        LIMIT 20
        """,
        (
            f"%{q}%",
            f"%{q}%",
            q,
            q
        )
    ).fetchall()

    connection.close()

    return {
        "users": [
            {
                "id": row["id"],
                "name": row["name"],
                "username": row["username"],
                "role": row["role"],
                "premium_level": row["premium_level"],
                "verified": bool(row["verified"])
            }
            for row in rows
            if row["id"] != current["id"]
        ]
    }

