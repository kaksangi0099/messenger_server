@app.post("/communities")
async def create_community(
    type: str,
    name: str,
    description: str = "",
    avatar_url: str | None = None,
    visibility: str = "private",
    username: str | None = None,
    authorization: str | None = Header(default=None)
):
    user = get_current_user(authorization)

    type = (type or "").strip().lower()
    name = (name or "").strip()
    description = (description or "").strip()
    visibility = (visibility or "private").strip().lower()
    username = (username or "").strip().lower().lstrip("@")
    avatar_url = (avatar_url or "").strip()

    if type not in ("group", "channel"):
        raise HTTPException(
            status_code=400,
            detail="نوع باید گروه یا کانال باشد."
        )

    if not name:
        raise HTTPException(
            status_code=400,
            detail="نام الزامی است."
        )

    if not avatar_url:
        raise HTTPException(
            status_code=400,
            detail="تصویر الزامی است."
        )

    if visibility not in ("public", "private"):
        raise HTTPException(
            status_code=400,
            detail="نوع دسترسی نامعتبر است."
        )

    if visibility == "public":
        if not username:
            raise HTTPException(
                status_code=400,
                detail="برای کانال یا گروه عمومی، نام کاربری الزامی است."
            )

        if len(username) < 3:
            raise HTTPException(
                status_code=400,
                detail="نام کاربری باید حداقل ۳ حرف باشد."
            )

        if not all(
            c.isalnum() or c == "_"
            for c in username
        ):
            raise HTTPException(
                status_code=400,
                detail="نام کاربری فقط می‌تواند شامل حروف، عدد و _ باشد."
            )
    else:
        username = None

    connection = db()

    try:
        if username:
            existing = connection.execute(
                """
                SELECT id
                FROM communities
                WHERE LOWER(username) = LOWER(%s)
                LIMIT 1
                """,
                (username,)
            ).fetchone()

            if existing:
                raise HTTPException(
                    status_code=409,
                    detail="این نام کاربری قبلاً استفاده شده است."
                )

        invite_token = secrets.token_urlsafe(18)

        row = connection.execute(
            """
            INSERT INTO communities
            (
                owner_id,
                type,
                name,
                description,
                avatar_url,
                visibility,
                username,
                invite_token,
                created_at
            )
            VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s)
            RETURNING id
            """,
            (
                user["id"],
                type,
                name,
                description,
                avatar_url,
                visibility,
                username,
                invite_token,
                datetime.now(timezone.utc).isoformat()
            )
        ).fetchone()

        community_id = row["id"]

        connection.execute(
            """
            INSERT INTO community_members
            (community_id, user_id, role, created_at)
            VALUES (%s,%s,%s,%s)
            """,
            (
                community_id,
                user["id"],
                "owner",
                datetime.now(timezone.utc).isoformat()
            )
        )

        connection.commit()

        if visibility == "public":
            link = f"/community/{username}"
        else:
            link = f"/join/{invite_token}"

        return {
            "message": "ساخته شد",
            "community": {
                "id": community_id,
                "type": type,
                "name": name,
                "description": description,
                "avatar_url": avatar_url,
                "visibility": visibility,
                "username": username,
                "invite_token": invite_token,
                "link": link
            }
        }

    except HTTPException:
        connection.rollback()
        raise
    except Exception as error:
        connection.rollback()
        print("CREATE COMMUNITY ERROR:", error)
        raise HTTPException(
            status_code=500,
            detail="ساخت گروه یا کانال انجام نشد."
        )
    finally:
        connection.close()



@app.post("/join/{invite_token}")
def join_community(
    invite_token: str,
    authorization: str | None = Header(default=None)
):
    user = get_current_user(authorization)
    c = db()

    community = c.execute(
        "SELECT * FROM communities WHERE invite_token=%s",
        (invite_token,)
    ).fetchone()

    if not community:
        c.close()
        raise HTTPException(status_code=404, detail="لینک دعوت معتبر نیست.")

    banned = c.execute(
        """
        SELECT id FROM community_bans
        WHERE community_id=%s AND user_id=%s
        """,
        (community["id"], user["id"])
    ).fetchone()

    if banned:
        c.close()
        raise HTTPException(status_code=403, detail="شما از این کانال حذف شده‌اید.")

    exists = c.execute(
        """
        SELECT id FROM community_members
        WHERE community_id=%s AND user_id=%s
        """,
        (community["id"], user["id"])
    ).fetchone()

    if not exists:
        c.execute(
            """
            INSERT INTO community_members
            (community_id,user_id,role,created_at)
            VALUES(%s,%s,'member',CURRENT_TIMESTAMP)
            """,
            (community["id"], user["id"])
        )
        c.commit()

    c.close()

    return {
        "ok": True,
        "community_id": community["id"],
        "name": community["name"]
    }

